# Creates .env for docker compose with fresh random secrets. Safe to re-run: it never overwrites an existing .env.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'
if (Test-Path $envFile) { Write-Host ".env already exists - leaving it untouched. Delete it first if you want new secrets (this will NOT reset existing databases)."; exit 0 }

function Rand([int]$n) {
  $chars = [char[]]('abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789')
  $bytes = New-Object byte[] $n; [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}
$platform = Rand 32
