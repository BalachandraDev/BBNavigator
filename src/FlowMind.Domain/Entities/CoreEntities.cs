using FlowMind.Domain.Enums;

namespace FlowMind.Domain.Entities;

/// <summary>Implemented by every entity that belongs to one tenant. Used by query filters and the write guard.</summary>
public interface ITenantOwned
{
    Guid TenantId { get; }
}

/// <summary>A customer company. Every other aggregate hangs off a tenant.</summary>
public class Tenant
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Name { get; set; } = "";
    public string Slug { get; set; } = "";
    public bool IsActive { get; set; } = true;
    /// <summary>First characters of the API key, for identification only.</summary>
    public string ApiKeyPrefix { get; set; } = "";
    /// <summary>SHA-256 (hex) of the tenant API key. The key itself is shown once and never stored.</summary>
    public string ApiKeyHash { get; set; } = "";
    /// <summary>The company key encrypted with the server secret (AES-GCM), so the platform admin can view it again. Null if it was created before this existed.</summary>
    public string? ApiKeyCipher { get; set; }
    /// <summary>Company-admin sign-ins issued before this moment are rejected (set when the key is reset).</summary>
    public DateTime? TokensValidAfterUtc { get; set; }
    public DateTime CreatedUtc { get; set; } = DateTime.UtcNow;
}

/// <summary>
/// A customer application whose documentation is ingested (e.g. "Hospital Management System").
/// Named TenantApplication to avoid clashing with the FlowMind.Application namespace.
/// </summary>
public class TenantApplication : ITenantOwned
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TenantId { get; set; }
    public string Name { get; set; } = "";
    public string? Description { get; set; }
    public DateTime CreatedUtc { get; set; } = DateTime.UtcNow;
}

public class Document : ITenantOwned
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TenantId { get; set; }
    public Guid ApplicationId { get; set; }
    public string FileName { get; set; } = "";
    public string ContentType { get; set; } = "";
    public DocumentStatus Status { get; set; } = DocumentStatus.Uploaded;
    public Guid? CurrentVersionId { get; set; }
    public DateTime CreatedUtc { get; set; } = DateTime.UtcNow;
    public DateTime? DeletedUtc { get; set; }
    public List<DocumentVersion> Versions { get; set; } = new();
}

/// <summary>One immutable upload of a document. The SHA-256 hash drives de-duplication.</summary>
public class DocumentVersion : ITenantOwned
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TenantId { get; set; }
    public Guid DocumentId { get; set; }
    public int VersionNumber { get; set; }
    public string ContentHash { get; set; } = "";
    public long SizeBytes { get; set; }
    /// <summary>Path relative to the storage root. Generated by the server, never derived from user input.</summary>
    public string StoragePath { get; set; } = "";
    /// <summary>Where the file is kept: "local" (this server's storage folder) or "remote" (the company's cloud storage from Settings). Old rows are "local".</summary>
    public string StorageKind { get; set; } = "local";
    public int? PageCount { get; set; }
    public DateTime CreatedUtc { get; set; } = DateTime.UtcNow;
}

/// <summary>Extracted text of one page (or DOCX/TXT page-equivalent) of a document version.</summary>
public class DocumentPage : ITenantOwned
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TenantId { get; set; }
    public Guid DocumentVersionId { get; set; }
    /// <summary>1-based page number used in citations.</summary>
    public int PageNumber { get; set; }
    public string Text { get; set; } = "";
    public PageTextSource Source { get; set; }
    public bool HasImages { get; set; }
    public int CharCount { get; set; }
}

public class DocumentProcessingJob : ITenantOwned
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public Guid TenantId { get; set; }
    public Guid DocumentVersionId { get; set; }
    public JobStage Stage { get; set; }
    public JobStatus Status { get; set; } = JobStatus.Pending;
    public int Attempts { get; set; }
    public string? Error { get; set; }
    public DateTime CreatedUtc { get; set; } = DateTime.UtcNow;
    public DateTime? NextAttemptUtc { get; set; }
    public DateTime? StartedUtc { get; set; }
    public DateTime? CompletedUtc { get; set; }
}

public class AIUsageLog
{
    public long Id { get; set; }
    public Guid? TenantId { get; set; }
    public AiProviderKind ProviderKind { get; set; }
    public string Provider { get; set; } = "";
    public string Model { get; set; } = "";
    public string Operation { get; set; } = "";
    public string Purpose { get; set; } = "";
    public int InputTokens { get; set; }
    public int OutputTokens { get; set; }
    public int OcrPages { get; set; }
    public decimal EmbeddingUnits { get; set; }
    public decimal EstimatedCostUsd { get; set; }
    public AiRequestStatus Status { get; set; }
    public string? ErrorMessage { get; set; }
    /// <summary>The share link whose visitor caused this call. Null for admin chat, access keys and document processing. Kept even if the link is later deleted.</summary>
    public Guid? BotLinkId { get; set; }
    public DateTime TimestampUtc { get; set; } = DateTime.UtcNow;
}

public class AuditLog
{
    public long Id { get; set; }
    public Guid? TenantId { get; set; }
    public string Actor { get; set; } = "";
    public string Action { get; set; } = "";
    public string? EntityType { get; set; }
    public string? EntityId { get; set; }
    public string? Detail { get; set; }
    public string? IpAddress { get; set; }
    public DateTime TimestampUtc { get; set; } = DateTime.UtcNow;
}
